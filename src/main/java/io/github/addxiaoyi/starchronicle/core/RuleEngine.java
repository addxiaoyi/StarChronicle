    private void validate(List<StoryDefinition> validatedDefinitions,DefinitionCatalog catalog){
        Set<String> ids=new HashSet<>();
        for(var d:validatedDefinitions){ConfigLoader.validate(d,id->true,id->true);if(!ids.add(d.id()))throw new IllegalArgumentException("Duplicate story ID");}
        if(validatedDefinitions.isEmpty())catalog.validateCurrent(validatedDefinitions);
        else ConfigLoader.validateAll(validatedDefinitions,catalog);
        if(npcs!=null)for(var d:validatedDefinitions)for(var n:d.nodes().values()) {
            validateNpcEffects(n.effects());for(var choice:n.choices().values())validateNpcEffects(choice.effects());
        }
    }
    private void validateNpcEffects(List<StoryDefinition.Effect> effects){for(var e:effects)if(Set.of("reputation","trust","hostility","growth","position").contains(e.type()))npcs.catalog().validateEffect(e.type(),e.target(),e.value());}

    public ProcessReport accept(WorldEvent event,Collection<PlayerContext> contexts) {
        Objects.requireNonNull(event);Objects.requireNonNull(contexts);
        if(event.facts().keySet().stream().anyMatch(EpicCampaignLedger.STORY_FACTS::contains))
            throw new SecurityException("Epic completion facts may only be emitted by a committed campaign transition");
        // An audience is distinct from historical actors: online citizens may witness a national
        // event without being listed as its direct participants in the permanent historical record.
        Map<UUID,PlayerContext> unique=new LinkedHashMap<>();
        for(var ctx:contexts) {
            if(!audience(event,ctx))
                throw new IllegalArgumentException("Context is neither a source participant nor a citizen of a participating nation");
            if(unique.put(ctx.playerId(),ctx)!=null) throw new IllegalArgumentException("Duplicate player context");
        }
        if(unique.size()>10000)throw new IllegalArgumentException("Too many trigger recipients");
        return transaction(c->{
            List<StoryDefinition> rules=runtime.enabledDefinitions();
            boolean fresh=recordAndQueue(c,event,unique.values(),rules,EventCausality.root(event.id()));
            Set<String> changed=drainTriggers(c,List.copyOf(unique.values()),event.id());
            return new ProcessReport(!fresh,List.copyOf(changed),fresh?"已记录事件与剧情变更":changed.isEmpty()?"事件已处理":"历史未重复，已恢复尚未交付的剧情触发");
        });
    }

    /** Commit a verified native national-aid receipt together with its canonical
     * history event, derived effects and durable story inbox.  The provider call
     * has already completed before entering this transaction; this method only
     * records evidence and never invokes StarCore. */
    public ProcessReport commitAid(io.github.addxiaoyi.starchronicle.api.aid.AidRequest request,
                                   io.github.addxiaoyi.starchronicle.api.aid.AidReceipt receipt,
                                   String issuer, String authorityDomain,
                                   Collection<PlayerContext> contexts) {
        Objects.requireNonNull(request); Objects.requireNonNull(receipt); Objects.requireNonNull(issuer);
        Objects.requireNonNull(authorityDomain); Objects.requireNonNull(contexts);
        if (!receipt.matches(request, issuer, authorityDomain)) throw new IllegalArgumentException("Native aid receipt does not match the pinned request");
        WorldEvent event=aidEvent(request, receipt, issuer, authorityDomain);
        Map<UUID,PlayerContext> unique=new LinkedHashMap<>();
        for (var ctx:contexts) {
            if (!audience(event,ctx)) throw new IllegalArgumentException("Context is not a valid aid audience");
            if (unique.put(ctx.playerId(), ctx)!=null) throw new IllegalArgumentException("Duplicate player context");
        }
        if (unique.isEmpty()) throw new IllegalArgumentException("Aid commit requires an online or source audience");
        return transaction(c->{
            boolean fresh=recordAndQueue(c,event,unique.values(),runtime.enabledDefinitions(),EventCausality.root(event.id()));
            Set<String> changed=drainTriggers(c,List.copyOf(unique.values()),event.id());
            AidLedger.commit(c,request,receipt,issuer,authorityDomain,event.id(),clock.instant());
            // The native receipt is the committed source timestamp. A fixed or slightly
            // lagging Chronicle clock must not make the local audit row predate that source.
            Instant recordedAt = clock.instant().isBefore(receipt.appliedAt())
                    ? receipt.appliedAt() : clock.instant();
            ContributionRequest nationContribution = new ContributionRequest(request.outcomeId(), ContributionType.RESOURCE_AID,
                    "nation:"+request.payerId(), event.id(), request.actorId(), request.payerId(), request.amount(),
                    "treasury", receipt.appliedAt(), "StarCore receipt issuer="+issuer+" domain="+authorityDomain+" transaction="+receipt.transactionId());
            ContributionLedger.record(c, nationContribution, recordedAt);
            ContributionRequest playerContribution = new ContributionRequest(request.outcomeId(), ContributionType.RESOURCE_AID,
                    "player:"+request.actorId(), event.id(), request.actorId(), request.payerId(), request.amount(),
                    "treasury", receipt.appliedAt(), "StarCore receipt issuer="+issuer+" domain="+authorityDomain+" transaction="+receipt.transactionId());
            ContributionLedger.record(c, playerContribution, recordedAt);
            return new ProcessReport(!fresh,List.copyOf(changed),fresh?"国库援助已记入世界历史并提交剧情收件箱":changed.isEmpty()?"国库援助历史已存在":"国库援助历史已存在，已恢复剧情触发");
        });
    }

    public static String aidEventId(String issuer,String transactionId){return "chronicle:aid:"+stable(issuer,transactionId);}
    private static WorldEvent aidEvent(io.github.addxiaoyi.starchronicle.api.aid.AidRequest request,
                                       io.github.addxiaoyi.starchronicle.api.aid.AidReceipt receipt,
                                       String issuer,String authorityDomain) {
        Map<String,String> facts=new LinkedHashMap<>();
        facts.put("aid.transaction",request.outcomeId()); facts.put("aid.issuer",issuer);
        facts.put("aid.authority_domain",authorityDomain); facts.put("aid.payer",request.payerId());
        facts.put("aid.receiver",request.receiverId()); facts.put("aid.amount",request.amount().toPlainString());
        facts.put("aid.category",receipt.category()); facts.put("aid.campaign",request.campaign());
        facts.put("aid.operation",request.operation()); facts.put("aid.definition",request.definitionFingerprint());
        facts.put("aid.applied_at",receipt.appliedAt().toString()); facts.put("time_basis","COMMITTED_SOURCE");
        String proof=stable("national-aid-proof",SqliteStore.json(receipt));
        return new WorldEvent(aidEventId(issuer,request.outcomeId()),"NATIONAL_AID_COMMITTED",receipt.appliedAt(),
                Set.of(request.actorId()),Set.of(request.payerId(),request.receiverId()),facts,issuer,
                "transaction="+request.outcomeId()+"; authority_domain="+authorityDomain+"; receipt_sha256="+proof+"; ledger=starcore.treasury.transfer");
    }

    private static boolean audience(WorldEvent event,PlayerContext context){return event.globalAudience()||event.participants().contains(context.playerId())||!context.nationId().isBlank()&&event.nations().contains(context.nationId());}
    private static String scope(StoryDefinition rule,PlayerContext context){return switch(rule.scope()){case PLAYER->"player:"+context.playerId();case NATION->context.nationId().isBlank()?null:"nation:"+context.nationId();case WORLD->"world";};}
    private static int queueTrigger(Connection c,StoryDefinition rule,WorldEvent event,Collection<PlayerContext> contexts)throws Exception {
        Set<String> seeds=new TreeSet<>();
        switch(rule.scope()) {
            case WORLD->seeds.add("world");
            case PLAYER->{event.participants().forEach(id->seeds.add("player:"+id));contexts.forEach(ctx->seeds.add("player:"+ctx.playerId()));event.nations().forEach(id->seeds.add("nation-players:"+id));if(event.globalAudience())seeds.add("players:*");}
            case NATION->{event.nations().forEach(id->seeds.add("nation:"+id));if(event.nations().isEmpty())event.participants().forEach(id->seeds.add("actor:"+id));contexts.stream().filter(ctx->!ctx.nationId().isBlank()&&(event.nations().isEmpty()||event.nations().contains(ctx.nationId()))).forEach(ctx->seeds.add("nation:"+ctx.nationId()));if(event.globalAudience()&&event.nations().isEmpty())seeds.add("nations:*");}
        }
        String trigger=stable(event.id(),rule.id(),rule.version());
        // A stable trigger key pins one exact graph. An old pending row cannot be
        // overwritten or silently hidden by a new graph using the same version.
        try(var s=c.prepareStatement("SELECT DISTINCT story_json FROM story_triggers WHERE trigger_key=?")) {
            s.setString(1,trigger);try(var r=s.executeQuery()){while(r.next())if(!json(decode(r.getString(1),StoryDefinition.class)).equals(json(rule)))throw new IllegalArgumentException("Conflicting pinned trigger definition: "+rule.id()+"/"+rule.version());}
        }
        int inserted=0;
        for(String seed:seeds) {
            if(seed.equals("world")||seed.startsWith("player:")||seed.startsWith("nation:")) {
                try(var s=c.prepareStatement("SELECT 1 FROM story_trigger_receipts WHERE trigger_key=? AND scope=?")) {
                    s.setString(1,trigger);s.setString(2,seed);try(var r=s.executeQuery()){if(r.next())continue;}
                }
            }
            try(var s=c.prepareStatement("INSERT OR IGNORE INTO story_triggers(id,trigger_key,event_id,scope,story_json) VALUES(?,?,?,?,?)")) {
                s.setString(1,stable(trigger,seed));s.setString(2,trigger);s.setString(3,event.id());s.setString(4,seed);s.setString(5,json(rule));inserted+=s.executeUpdate();
            }
        }
        return inserted;
    }
    /** Explicitly register only this saved source and exact enabled version. Execution is
     * deferred to normal fresh-context polling; this never resubmits the source, applies
     * its NPC reactions again, or invents the identities that existed at its old time. */
    public HistoricalEvaluationReport evaluateHistorical(String sourceId,String storyId,String expectedVersion) {
        Objects.requireNonNull(sourceId);Objects.requireNonNull(storyId);Objects.requireNonNull(expectedVersion);
        return transaction(c->{
            StoryDefinition rule=runtime.enabledDefinitions().stream().filter(d->d.id().equals(storyId)&&d.version().equals(expectedVersion)).findFirst().orElseThrow(()->new IllegalArgumentException("No enabled exact story version: "+storyId+"/"+expectedVersion));
            WorldEvent source;
            try(var s=c.prepareStatement("SELECT json FROM events WHERE id=?")) {
                s.setString(1,sourceId);try(var r=s.executeQuery()){if(!r.next())throw new IllegalArgumentException("No saved canonical source event: "+sourceId);source=decode(r.getString(1),WorldEvent.class);}
            }
            if(!rule.triggers().contains(source.type()))throw new IllegalArgumentException("Canonical event type does not trigger this story version");
            long matching=0,completed=0;
            try(var s=c.prepareStatement("SELECT completed FROM instances WHERE story=? AND json_extract(json,'$.definition.version')=? AND json_extract(json,'$.sourceEventId')=?")) {
                s.setString(1,storyId);s.setString(2,expectedVersion);s.setString(3,sourceId);try(var r=s.executeQuery()){while(r.next()){matching++;if(r.getBoolean(1))completed++;}}
            }
            String blocked=EventCausality.blockedReason(EventCausality.read(c,sourceId),storyId);
            if(blocked!=null) {
                EventCausality.block(c,sourceId,rule,blocked);
                return new HistoricalEvaluationReport(sourceId,storyId,expectedVersion,HistoricalEvaluationReport.Status.BLOCKED_CAUSAL,0,matching,completed,blocked);
            }
            if(source.participants().isEmpty()&&source.nations().isEmpty()&&!source.globalAudience())
                return new HistoricalEvaluationReport(sourceId,storyId,expectedVersion,HistoricalEvaluationReport.Status.NO_SOURCE_AUDIENCE,0,matching,completed,"来源没有参与者、国家或显式全服受众；不会补造历史身份");
            int inserted=queueTrigger(c,rule,source,List.of());
            String key=stable(sourceId,storyId,expectedVersion);boolean registered;
            try(var s=c.prepareStatement("SELECT 1 FROM story_triggers WHERE trigger_key=? UNION ALL SELECT 1 FROM story_trigger_receipts WHERE trigger_key=? LIMIT 1")) {
                s.setString(1,key);s.setString(2,key);try(var r=s.executeQuery()){registered=r.next();}
            }
            var status=inserted>0?HistoricalEvaluationReport.Status.QUEUED:registered?HistoricalEvaluationReport.Status.ALREADY_REGISTERED:HistoricalEvaluationReport.Status.NO_SOURCE_AUDIENCE;
            return new HistoricalEvaluationReport(sourceId,storyId,expectedVersion,status,inserted,matching,completed,"仅登记持久触发；按当前真实身份、完成实例、冷却、版本与权限复核，未立即执行剧情或奖励");
        });
    }
    private record PendingTrigger(String id,String triggerKey,String eventId,String seed,StoryDefinition definition){}
    private static Set<String> audienceSeeds(Collection<PlayerContext> contexts){Set<String> seeds=new HashSet<>(Set.of("world","players:*","nations:*"));for(var ctx:contexts){seeds.add("player:"+ctx.playerId());seeds.add("actor:"+ctx.playerId());if(!ctx.nationId().isBlank()){seeds.add("nation:"+ctx.nationId());seeds.add("nation-players:"+ctx.nationId());}}return seeds;}
    /** Event acceptance and this durable inbox commit together. A lack of online audience is
     * not a consumed plot result. Call with fresh server snapshots on join and worker polling. */
    public ProcessReport resumeTriggers(Collection<PlayerContext> contexts){
        Map<UUID,PlayerContext> unique=new LinkedHashMap<>();for(var ctx:contexts)if(unique.put(ctx.playerId(),ctx)!=null)throw new IllegalArgumentException("Duplicate player context");
        if(unique.isEmpty())return new ProcessReport(false,List.of(),"暂无在线剧情受众");
        if(unique.size()>10000)throw new IllegalArgumentException("Too many trigger recipients");
        return transaction(c->{
            observeMembers(c, unique.values());
            List<PlayerContext> current=List.copyOf(unique.values());Set<String> changed=drainTriggers(c,current,null);
            Set<String> scopes=new HashSet<>(Set.of("world"));for(var ctx:current){scopes.add("player:"+ctx.playerId());if(!ctx.nationId().isBlank())scopes.add("nation:"+ctx.nationId());}
            String marks=String.join(",",Collections.nCopies(scopes.size(),"?"));List<StoryInstance> active=new ArrayList<>();
            try(var s=c.prepareStatement("SELECT json FROM instances WHERE completed=0 AND scope IN ("+marks+") ORDER BY id")){int p=1;for(String key:scopes)s.setString(p++,key);try(var r=s.executeQuery()){while(r.next())active.add(decode(r.getString(1),StoryInstance.class));}}
            for(StoryInstance instance:active) {
                WorldEvent origin=event(c,instance.sourceEventId());
                for(var ctx:current)if(!instance.contains(ctx.playerId())&&audience(origin,ctx)&&Objects.equals(instance.scopeKey(),scope(instance.definition(),ctx))&&eligible(c,instance,ctx,origin)){
                    instance=addMember(c,instance,ctx,origin);changed.add(instance.id());
                }
            }
            return new ProcessReport(false,List.copyOf(changed),"已恢复持久化剧情触发与相关参与者");
        });
    }
    public List<StoryDefinition> pendingDefinitions(){return transaction(c->{List<StoryDefinition> result=new ArrayList<>();try(var s=c.createStatement();var r=s.executeQuery("SELECT DISTINCT story_json FROM story_triggers")){while(r.next())result.add(decode(r.getString(1),StoryDefinition.class));}return List.copyOf(result);});}
