    /** One source transaction owns history, NPC feedback, causal evidence and the durable
     * follow-up inbox. Derived history never recursively invokes accept or starts an instance. */
    private boolean recordAndQueue(Connection c,WorldEvent event,Collection<PlayerContext> contexts,List<StoryDefinition> rules,EventCausality.Trace trace)throws Exception {
        if(!record(c,event))return false;
        EventCausality.record(c,event.id(),trace);
        // Background recipes share this transaction even when nobody is online. Only their
        // evidenced fixed signal is queued; ordinary story activation remains in the existing inbox.
        for(var recipe:memoryRecipes.recipes())if(recipe.matches(event)) {
            String reason=EventCausality.blockedRecipeReason(trace,recipe.id());
            MemoryBudget budget=Objects.requireNonNull(memoryBudget.get(),"Recipe work requires its top-level transaction budget");
            if(reason==null&&budget.generated>=MAX_MEMORY_SIGNALS_PER_TRANSACTION)reason="MAX_MEMORY_SIGNALS_PER_TRANSACTION";
            if(reason!=null){MemoryRecipeLedger.block(c,event,recipe,reason);continue;}
            budget.generated++;
            var entry=MemoryRecipeLedger.register(c,recipe,event,clock.instant());
            if(!recordAndQueue(c,MemoryRecipeLedger.signal(entry,event),contexts,rules,EventCausality.deriveRecipe(c,event.id(),recipe.id())))
                throw new IllegalStateException("Memory signal already exists without this source transaction: "+entry.signalEventId());
        }
        for(var rule:rules)if(rule.triggers().contains(event.type())) {
            String reason=EventCausality.blockedReason(trace,rule.id());
            if(reason==null)queueTrigger(c,rule,event,contexts);else EventCausality.block(c,event.id(),rule,reason);
        }
        return true;
    }
