        try(var s=c.prepareStatement("INSERT INTO events VALUES(?,?,?,?,?)")){s.setString(1,e.id());s.setString(2,e.type());s.setString(3,SORTABLE_TIME.format(e.occurredAt()));s.setString(4,hash);s.setString(5,json(e));s.executeUpdate();}
