    /** One budget covers every recipe signal generated by this complete SQL operation,
     * including multiple story effects and all recursive recipe branches. */
    private <T>T transaction(SqliteStore.Work<T> work) {
        // Reject reentry before SqliteStore touches autoCommit/rollback on this connection.
        if(memoryBudget.get()!=null)throw new IllegalStateException("Nested rule transactions are not supported");
        return store.transaction(c->{
            memoryBudget.set(new MemoryBudget());
            try{return work.run(c);}finally{memoryBudget.remove();}
        });
    }
